def definition_by_code() -> dict[str, dict[str, object]]:
    return {str(item["code"]): item for item in SKILL_DEFINITIONS}


def child_skills_for_parent(parent_code: str) -> list[dict[str, object]]:
    children = [
        item for item in SKILL_DEFINITIONS if item.get("parent_code") == parent_code
    ]
    return sorted(children, key=lambda item: int(item["progression_position"]))


def is_academic_code(code: str) -> bool:
    return code.startswith(("math.", "reading.", "writing."))


def is_growth_or_life_code(code: str) -> bool:
    return code.startswith(("growth.", "life."))


def is_generation_supported(code: str) -> bool:
    return code not in UNSUPPORTED_FOR_GENERATION

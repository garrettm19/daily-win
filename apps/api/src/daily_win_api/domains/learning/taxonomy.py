UNSUPPORTED_FOR_GENERATION: frozenset[str] = frozenset()


def _strand(
    code: str,
    domain: SkillDomain,
    display_name: str,
    description: str,
    *,
    strand: str,
    state_mode: SkillStateMode,
) -> dict[str, object]:
    return {
        "code": code,
        "domain": domain.value,
        "display_name": display_name,
        "description": description,
        "state_mode": state_mode.value,
        "skill_kind": SkillKind.STRAND.value,
        "strand": strand,
        "parent_code": None,
        "grade_band_min": 5,
        "grade_band_max": 9,
        "measurable_outcome": None,
        "progression_position": 0,
        "taxonomy_version": TAXONOMY_VERSION,
    }


def _skill(
    code: str,
    parent_code: str,
    domain: SkillDomain,
    strand: str,
    display_name: str,
    description: str,
    *,
    position: int,
    grade_min: int,
    grade_max: int,
    outcome: str,
) -> dict[str, object]:
    return {
        "code": code,
        "domain": domain.value,
        "display_name": display_name,
        "description": description,
        "state_mode": SkillStateMode.MASTERY.value,
        "skill_kind": SkillKind.SKILL.value,
        "strand": strand,
        "parent_code": parent_code,
        "grade_band_min": grade_min,
        "grade_band_max": grade_max,
        "measurable_outcome": outcome,
        "progression_position": position,
        "taxonomy_version": TAXONOMY_VERSION,
    }



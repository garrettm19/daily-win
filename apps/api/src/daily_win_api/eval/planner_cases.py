def evaluate_planner_case(case: PlannerCase) -> list[str]:
    plan = plan_instruction_v3(case.data)
    errors: list[str] = []
    if plan.primary_skill_code != case.expected_skill:
        errors.append(f"skill {plan.primary_skill_code} != {case.expected_skill}")
    if plan.primary_skill_code in case.forbid:
        errors.append(f"selected forbidden skill {plan.primary_skill_code}")
    if plan.instruction_mode is not case.expected_mode:
        errors.append(f"mode {plan.instruction_mode} != {case.expected_mode}")
    if plan.intended_difficulty != case.expected_difficulty:
        errors.append(
            f"difficulty {plan.intended_difficulty} != {case.expected_difficulty}"
        )
    if plan.scaffold_level is not case.expected_scaffold:
        errors.append(f"scaffold {plan.scaffold_level} != {case.expected_scaffold}")
    missing_reasons = [
        code
        for code in case.expected_reason_subset
        if code not in plan.selection_reason_codes
    ]
    if missing_reasons:
        errors.append(f"missing reasons {missing_reasons}")
    if case.assessment_contains.lower() not in plan.assessment_objective.lower():
        errors.append(
            f"assessment {plan.assessment_objective!r} missing "
            f"{case.assessment_contains!r}"
        )
    if plan.assessment_probe.get("target_skill_code") not in {
        case.expected_skill,
        plan.primary_skill_code,
    }:
        errors.append("probe target mismatch")
    if plan.policy_version != "instruction_policy_v3":
        errors.append("policy version drift")
    if plan.placement_policy_version != "placement_policy_v1":
        errors.append("placement policy version drift")
    expected_minutes = max(10, min(25, case.data.preferred_duration_minutes))
    if plan.duration_minutes != expected_minutes:
        errors.append(f"duration {plan.duration_minutes} != {expected_minutes}")
    if plan.supporting_skill_code in case.forbid_supporting:
        errors.append(f"supporting {plan.supporting_skill_code} is forbidden")
    return errors

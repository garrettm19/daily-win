A = AcademicBand
M = InstructionMode
S = ScaffoldLevel


@dataclass(frozen=True)
class PlannerCase:
    id: str
    label: str
    data: PlannerInput
    expected_skill: str
    expected_mode: InstructionMode
    expected_difficulty: str
    expected_scaffold: ScaffoldLevel
    expected_reason_subset: tuple[str, ...]
    assessment_contains: str
    forbid: tuple[str, ...] = ()
    forbid_supporting: tuple[str, ...] = ()


def _ready(*codes: str) -> tuple:
    return tuple(state(code, A.RETAINED, sessions=4) for code in codes)


def _prereq_codes(skill_code: str) -> tuple[str, ...]:
    found: list[str] = []

    def walk(code: str) -> None:
        for prereq in prerequisites_for(code):
            walk(prereq)
            if prereq not in found:
                found.append(prereq)

    walk(skill_code)
    return tuple(found)


def _states_for(expect: str, ready: tuple[str, ...], states: tuple) -> tuple:
    existing = {item.skill_code for item in states} | set(ready)
    needed = tuple(code for code in _prereq_codes(expect) if code not in existing)
    return _ready(*needed, *ready) + states


def _case(
    case_id: str,
    label: str,
    *,
    age: int,
    grade: str,
    goals: tuple[tuple[str, int], ...],
    expect: str,
    mode: InstructionMode,
    difficulty: str,
    scaffold: ScaffoldLevel,
    reasons: tuple[str, ...],
    assessment: str,
    states: tuple = (),
    ready: tuple[str, ...] = (),
    interests: tuple[str, ...] = ("space",),
    forbid: tuple[str, ...] = (),
    forbid_supporting: tuple[str, ...] = (),
    recent_skills: tuple[str, ...] = (),
    recent_themes: tuple[str, ...] = (),
    minutes: int = 20,
    nickname: str = "Nova",
    auto_ready: bool = True,
) -> PlannerCase:
    if auto_ready:
        resolved = _states_for(expect, ready, states)
    elif ready:
        resolved = _ready(*ready) + states
    else:
        resolved = states
    return PlannerCase(
        id=case_id,
        label=label,
        data=planner_input(
            nickname=nickname,
            age_years=age,
            grade=grade,
            interests=interests,
            minutes=minutes,
            goals=goals,
            states=resolved,
            recent_skills=recent_skills,
            recent_themes=recent_themes,
        ),
        expected_skill=expect,
        expected_mode=mode,
        expected_difficulty=difficulty,
        expected_scaffold=scaffold,
        expected_reason_subset=reasons,
        assessment_contains=assessment,
        forbid=forbid,
        forbid_supporting=forbid_supporting,
    )


